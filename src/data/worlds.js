export const getWorldById = (id) => WORLDS.find(w => w.id === id);
export const getWorldByOrder = (order) => WORLDS.find(w => w.order === order);
export const getNextWorld = (currentId) => {
  const current = getWorldById(currentId);
  if (!current) return null;
  return WORLDS.find(w => w.order === current.order + 1) || null;
};
